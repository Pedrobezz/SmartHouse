const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getAll: () => ipcRenderer.invoke('get-all'),
  command: (id, cmd) => ipcRenderer.invoke('command', id, cmd),
  runAction: a => ipcRenderer.invoke('run-action', a),
  runScene: id => ipcRenderer.invoke('run-scene', id),
  deviceProfile: id => ipcRenderer.invoke('device-profile', id),
  getEnergy: id => ipcRenderer.invoke('get-energy', id),
  save: (key, value) => ipcRenderer.invoke('save', key, value),
  backupExport: () => ipcRenderer.invoke('backup-export'),
  backupImport: () => ipcRenderer.invoke('backup-import'),
  rename: (id, name) => ipcRenderer.invoke('rename', id, name),
  saveSettings: s => ipcRenderer.invoke('save-settings', s),
  tuyaScan: () => ipcRenderer.invoke('tuya-scan'),
  tuyaAdd: rec => ipcRenderer.invoke('tuya-add', rec),
  tuyaRemove: id => ipcRenderer.invoke('tuya-remove', id),
  ewelinkLogin: cfg => ipcRenderer.invoke('ewelink-login', cfg),
  ewelinkLogout: () => ipcRenderer.invoke('ewelink-logout'),
  openMini: () => ipcRenderer.invoke('mini-open'),
  closeMini: () => ipcRenderer.invoke('mini-close'),
  pinMini: on => ipcRenderer.invoke('mini-pin', on),
  miniHeight: h => ipcRenderer.invoke('mini-height', h),
  openMain: () => ipcRenderer.invoke('open-main'),
  updaterState: () => ipcRenderer.invoke('updater-state'),
  updaterCheck: () => ipcRenderer.invoke('updater-check'),
  setSeenVersion: v => ipcRenderer.invoke('seen-version', v),
  updaterInstall: () => ipcRenderer.invoke('updater-install'),
  onUpdater: cb => ipcRenderer.on('updater', (_, d) => cb(d)),
  setTheme: t => ipcRenderer.invoke('set-theme', t),
  setZoom: z => ipcRenderer.invoke('set-zoom', z),
  mobileInfo: () => ipcRenderer.invoke('mobile-info'),
  mobileRegen: () => ipcRenderer.invoke('mobile-regen'),
  mobileTestPush: () => ipcRenderer.invoke('mobile-test-push'),
  onSaved: cb => ipcRenderer.on('saved', (_, k) => cb(k)),
  resetLayout: () => ipcRenderer.invoke('reset-layout'),
  onUpdate: cb => ipcRenderer.on('update', (_, d) => cb(d)),
  onLog: cb => ipcRenderer.on('log', (_, d) => cb(d)),
});
